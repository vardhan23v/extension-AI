// Extracts and structurally validates the JSON object returned by a model.
const extractJson = (text) => {
  const stripped = String(text).replace(/```(?:json)?\s*/gi, '').replace(/```/g, '');
  const start = stripped.indexOf('{');
  const end = stripped.lastIndexOf('}');
  if (start === -1 || end <= start) throw new Error('AI output did not contain a JSON object');
  try {
    return JSON.parse(stripped.slice(start, end + 1));
  } catch {
    throw new Error('AI output was not valid JSON');
  }
};

const parseExtensionResponse = (text) => {
  const parsed = extractJson(text);
  if (typeof parsed.title !== 'string' || !parsed.title.trim()) throw new Error('AI response is missing "title"');
  if (!Array.isArray(parsed.files) || parsed.files.length === 0) throw new Error('AI response contains no files');
  // Models sometimes list image files (e.g. icons) without content; icons are
  // generated by the platform, so drop those entries instead of failing.
  parsed.files = parsed.files.filter(
    (f) => !(f && typeof f.filename === 'string' && /\.(png|jpe?g|gif|webp|ico)$/i.test(f.filename) && typeof f.content !== 'string')
  );
  if (parsed.files.length === 0) throw new Error('AI response contains no files');
  for (const f of parsed.files) {
    if (!f || typeof f.filename !== 'string' || (typeof f.content !== 'string' && typeof f.content !== 'object')) {
      throw new Error('AI response contains a malformed file entry');
    }
  }
  return {
    title: parsed.title.trim().slice(0, 200),
    storeDescription: typeof parsed.storeDescription === 'string' ? parsed.storeDescription.slice(0, 1000) : '',
    summary: typeof parsed.summary === 'string' ? parsed.summary.slice(0, 2000) : '',
    files: parsed.files.map((f) => ({ filename: f.filename, content: f.content })),
  };
};

module.exports = { extractJson, parseExtensionResponse };
