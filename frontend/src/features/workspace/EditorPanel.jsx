import React, { useEffect, useRef } from 'react';
import Editor, { DiffEditor } from '@monaco-editor/react';
import { X, Wand2 } from 'lucide-react';
import './monaco';
import { useTheme } from '../../context/ThemeContext';
import { languageFor, isBinary } from '../../lib/files';
import { IconButton, Spinner, cx } from '../../components/ui';

const MIME = { png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg', gif: 'image/gif', webp: 'image/webp', ico: 'image/x-icon' };

const OPTIONS = {
  fontFamily: '"JetBrains Mono", ui-monospace, Menlo, monospace',
  fontSize: 13,
  lineHeight: 20,
  minimap: { enabled: false },
  scrollBeyondLastLine: false,
  automaticLayout: true,
  tabSize: 2,
  wordWrap: 'on',
  renderLineHighlight: 'line',
  padding: { top: 12 },
  smoothScrolling: true,
  fixedOverflowWidgets: true,
};

const BinaryView = ({ file }) => {
  const ext = file.filename.split('.').pop().toLowerCase();
  return (
    <div className="flex h-full flex-col items-center justify-center gap-3 text-sm text-muted">
      <img src={`data:${MIME[ext] || 'image/png'};base64,${file.content}`} alt={file.filename} className="h-24 w-24 rounded border border-border object-contain bg-surface p-2" />
      <p>{file.filename} — binary file, generated by the platform.</p>
    </div>
  );
};

export const EditorTabs = ({ tabs, active, onSelect, onClose, dirtyNames }) => (
  <div role="tablist" aria-label="Open files" className="flex h-10 shrink-0 items-end overflow-x-auto border-b border-border bg-surface">
    {tabs.map((name) => {
      const isActive = name === active;
      return (
        <div
          key={name}
          className={cx(
            'group flex h-full items-center border-r border-border text-[13px]',
            isActive ? 'bg-bg text-fg' : 'text-muted hover:text-fg'
          )}
        >
          <button role="tab" type="button" aria-selected={isActive} onClick={() => onSelect(name)} className="h-full pl-3 pr-1 font-mono text-[12px]">
            {name.split('/').pop()}
            {dirtyNames?.has(name) && <span className="ml-1 text-primary" aria-label="unsaved">•</span>}
          </button>
          <IconButton label={`Close ${name}`} size="icon-sm" className="mr-1 h-6 w-6 opacity-60 group-hover:opacity-100" onClick={() => onClose(name)}>
            <X className="h-3 w-3" />
          </IconButton>
        </div>
      );
    })}
  </div>
);

export const EditorPanel = ({ file, onChange, onSave, revealLine, readOnly = false }) => {
  const { theme } = useTheme();
  const editorRef = useRef(null);
  const saveRef = useRef(onSave);
  saveRef.current = onSave;

  useEffect(() => {
    if (revealLine && editorRef.current) {
      editorRef.current.revealLineInCenter(revealLine);
      editorRef.current.setPosition({ lineNumber: revealLine, column: 1 });
      editorRef.current.focus();
    }
  }, [revealLine, file?.filename]);

  if (!file) {
    return <div className="flex h-full items-center justify-center text-sm text-muted">Select a file to start editing.</div>;
  }
  if (isBinary(file)) return <BinaryView file={file} />;

  return (
    <div className="relative h-full">
      <Editor
        path={file.filename}
        defaultLanguage={languageFor(file.filename)}
        language={languageFor(file.filename)}
        value={file.content}
        theme={theme === 'dark' ? 'vs-dark' : 'vs'}
        options={{ ...OPTIONS, readOnly }}
        loading={<Spinner label="Loading editor" />}
        onChange={(v) => onChange(file.filename, v ?? '')}
        onMount={(editor, monaco) => {
          editorRef.current = editor;
          editor.addCommand(monaco.KeyMod.CtrlCmd | monaco.KeyCode.KeyS, () => saveRef.current?.());
        }}
      />
      {!readOnly && (
        <IconButton
          label="Format document"
          size="icon-sm"
          variant="secondary"
          className="absolute bottom-3 right-5 shadow-sm"
          onClick={() => editorRef.current?.getAction('editor.action.formatDocument')?.run()}
        >
          <Wand2 className="h-3.5 w-3.5" />
        </IconButton>
      )}
    </div>
  );
};

export const DiffPanel = ({ filename, original, modified }) => {
  const { theme } = useTheme();
  return (
    <DiffEditor
      original={original ?? ''}
      modified={modified ?? ''}
      language={languageFor(filename)}
      originalModelPath={`original/${filename}`}
      modifiedModelPath={`proposed/${filename}`}
      theme={theme === 'dark' ? 'vs-dark' : 'vs'}
      options={{ ...OPTIONS, readOnly: true, renderSideBySide: window.innerWidth > 900 }}
      loading={<Spinner label="Loading diff" />}
    />
  );
};
